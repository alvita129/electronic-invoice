CREATE OR REPLACE FUNCTION prevent_audit_trail_mutation() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'Audit trail records are immutable';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER audit_trails_immutable
    BEFORE UPDATE OR DELETE ON AUDIT_TRAILS
    FOR EACH ROW EXECUTE FUNCTION prevent_audit_trail_mutation();

ALTER TABLE AUDIT_TRAILS DROP CONSTRAINT IF EXISTS FK_AUDIT_INVOICE;
ALTER TABLE AUDIT_TRAILS ADD CONSTRAINT FK_AUDIT_INVOICE
    FOREIGN KEY (INVOICE_ID) REFERENCES MST_INVOICES(INVOICE_ID);
